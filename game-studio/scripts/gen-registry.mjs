#!/usr/bin/env node
// Scans src/games/* and writes src/lib/registry.generated.js so adding a game is
// just "drop a folder in src/games". Runs automatically before dev/build.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const gamesDir = path.join(root, 'src/games');
const slugs = fs
  .readdirSync(gamesDir)
  .filter((d) => d !== 'engine' && fs.existsSync(path.join(gamesDir, d, 'index.js')) && fs.existsSync(path.join(gamesDir, d, 'meta.js')))
  .sort();

const ident = (s) => 'm_' + s.replace(/[^a-z0-9]/gi, '_');
const lines = [
  '// AUTO-GENERATED by scripts/gen-registry.mjs - do not edit by hand.',
  ...slugs.map((s) => `import ${ident(s)} from '@/games/${s}/meta.js';`),
  '',
  `export const ALL_META = [${slugs.map(ident).join(', ')}];`,
  '',
  'export const LOADERS = {',
  ...slugs.map((s) => `  '${s}': () => Promise.all([import('@/games/${s}/index.js'), import('@/games/${s}/meta.js')]),`),
  '};',
  '',
  '// Games with a recorded gameplay loop in public/clips (scripts/clips.mjs).',
  `export const CLIPS = new Set(${JSON.stringify(slugs.filter((s) => ['mp4', 'webm', 'webp'].every((e) => fs.existsSync(path.join(root, 'public/clips', `${s}.${e}`)))))});`,
  '',
];
fs.writeFileSync(path.join(root, 'src/lib/registry.generated.js'), lines.join('\n'));
console.log(`registry: ${slugs.length} games (${slugs.join(', ')})`);
console.log(`clips: ${slugs.filter((s) => fs.existsSync(path.join(root, 'public/clips', `${s}.mp4`))).length}`);
